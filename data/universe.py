# ── Official NSE index constituents (static file, no network at import) ──────
# data/nse_index_constituents.csv is regenerated by tools/refresh_universe.py
# from NSE's official constituent CSVs. Columns: Symbol, Company, Industry,
# Index — Index is the narrowest tier (NIFTY50 > NEXT50 > MIDCAP150 >
# SMALLCAP250 > MICROCAP250 > TOTALMARKET).
_CONSTITUENTS_CSV = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                 "nse_index_constituents.csv")


def _load_constituents() -> List[Dict[str, str]]:
    try:
        with open(_CONSTITUENTS_CSV, encoding="utf-8", newline="") as f:
            return [r for r in csv.DictReader(f) if (r.get("Symbol") or "").strip()]
    except OSError:
        return []


_CONSTITUENTS: List[Dict[str, str]] = _load_constituents()


def _tier(name: str) -> List[str]:
    return [r["Symbol"].strip() + ".NS" for r in _CONSTITUENTS if r.get("Index") == name]


# Official NIFTY 50; falls back to fetcher's static list if the CSV is missing.
